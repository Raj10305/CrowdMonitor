package com.example.myapplication.models;

public class HistoryItem {
    public String timestamp;
    public int count;
    public String filename;
    public String url;

    public String getTimestamp() {
        return timestamp;
    }

    public int getCount() {
        return count;
    }

    public String getFilename() {
        return filename;
    }

    public String getUrl() {
        return url;
    }
}
